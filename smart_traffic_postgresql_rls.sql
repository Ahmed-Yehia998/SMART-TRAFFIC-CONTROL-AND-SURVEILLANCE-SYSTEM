CREATE DATABASE test;

CREATE TYPE intersection_status_enum AS ENUM ('active', 'inactive');

CREATE TYPE road_direction_enum AS ENUM ('north', 'south', 'east', 'west');

CREATE TYPE camera_status_enum AS ENUM ('Online', 'Offline', 'Maintenance');

CREATE TYPE camera_type_enum AS ENUM ('Traffic', 'Surveillance');

CREATE TYPE vehicle_type_enum AS ENUM (
    'Car', 'Bus', 'Ambulance', 'Motorcycle',
    'Truck', 'Fire_Truck', 'Police'
);

CREATE TYPE traffic_light_state_enum AS ENUM ('Red', 'Yellow', 'Green');

CREATE TYPE pedestrian_request_status_enum AS ENUM (
    'Waiting', 'Approved', 'Crossing', 'Completed', 'Cancelled'
);

CREATE TYPE congestion_level_enum AS ENUM ('Low', 'Medium', 'High');

CREATE TYPE alert_type_enum AS ENUM (
    'Accident', 'Emergency', 'Speed_Violation', 'Device_Failure'
);

CREATE TYPE alert_status_enum AS ENUM ('New', 'Under_Review', 'Resolved');

CREATE TABLE intersections (
    intersection_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intersection_name VARCHAR(50),
    intersection_location VARCHAR(50),
    intersection_status intersection_status_enum DEFAULT 'active'
);

CREATE TABLE roads (
    road_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    road_name VARCHAR(50),
    direction road_direction_enum NOT NULL
);

CREATE TABLE intersection_road (
    road_id INT,
    intersection_id INT,

    PRIMARY KEY (road_id, intersection_id),

    FOREIGN KEY (road_id)
        REFERENCES roads(road_id),

    FOREIGN KEY (intersection_id)
        REFERENCES intersections(intersection_id)
);

CREATE TABLE cameras (
    camera_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_name VARCHAR(50),
    camera_status camera_status_enum DEFAULT 'Online',
    camera_type camera_type_enum,

    intersection_id INT,

    FOREIGN KEY (intersection_id)
        REFERENCES intersections(intersection_id)
);

CREATE TABLE road_cameras (
    road_id INT,
    camera_id INT,

    PRIMARY KEY (road_id, camera_id),

    FOREIGN KEY (road_id)
        REFERENCES roads(road_id),

    FOREIGN KEY (camera_id)
        REFERENCES cameras(camera_id)
);

CREATE TABLE vehicles (
    vehicle_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_code VARCHAR(50) NOT NULL UNIQUE,
    vehicle_type vehicle_type_enum DEFAULT 'Car'
);

CREATE TABLE traffic_light (
    traffic_light_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    current_state traffic_light_state_enum DEFAULT 'Red'
);

CREATE TABLE pedestrian_requests (
    request_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_status pedestrian_request_status_enum DEFAULT 'Waiting',

    request_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP DEFAULT NULL,

    intersection_id INT,

    FOREIGN KEY (intersection_id)
        REFERENCES intersections(intersection_id)
);

CREATE TABLE traffic_status (
    record_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    congestion_level congestion_level_enum DEFAULT 'Low',
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    vehicle_count INT NOT NULL DEFAULT 0,

    camera_id INT,

    FOREIGN KEY (camera_id)
        REFERENCES cameras(camera_id)
);

CREATE TABLE alerts (
    alert_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    alert_type alert_type_enum NOT NULL,
    description VARCHAR(255),
    status alert_status_enum DEFAULT 'New',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    request_id INT,

    FOREIGN KEY (request_id)
        REFERENCES pedestrian_requests(request_id)
);

CREATE TABLE alert_vehicles (
    alert_id INT,
    vehicle_id INT,

    PRIMARY KEY (alert_id, vehicle_id),

    FOREIGN KEY (alert_id)
        REFERENCES alerts(alert_id),

    FOREIGN KEY (vehicle_id)
        REFERENCES vehicles(vehicle_id)
);

CREATE TABLE alert_traffic_light (
    alert_id INT,
    traffic_light_id INT,

    PRIMARY KEY (alert_id, traffic_light_id),

    FOREIGN KEY (alert_id)
        REFERENCES alerts(alert_id),

    FOREIGN KEY (traffic_light_id)
        REFERENCES traffic_light(traffic_light_id)
);

CREATE TABLE traffic_status_traffic_light (
    record_id INT,
    traffic_light_id INT,

    PRIMARY KEY (record_id, traffic_light_id),

    FOREIGN KEY (record_id)
        REFERENCES traffic_status(record_id),

    FOREIGN KEY (traffic_light_id)
        REFERENCES traffic_light(traffic_light_id)
);

